# tools/data/build_dataset.py
"""
Build a training-ready dataset from a manifest.

    python -m tools.data.build_dataset \
        --manifest data/manifests/person_detection_woodscape_version_1.yaml

Reads the manifest, verifies the source data on disk matches its recorded
statistics, generates the split, converts annotations to the training
format, and writes build_info.json recording exactly what produced the
build. Everything under data/build/<manifest name>/ is disposable and
regenerated by this script.
"""
from __future__ import annotations

import argparse
import json
import random
import shutil
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

from PIL import Image

from engine.data_manifest import (
    DataManifest,
    load_manifest,
    verify_source_matches_statistics,
)
from engine.provenance import git_commit, git_is_dirty, hash_file
from src.data.source_readers import SourceAnnotation, get_reader

IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg"}

# WoodScape encodes camera position as a filename suffix. Spelled out here
# so that no abbreviation reaches the manifest or the build metadata.
CAMERA_POSITION_BY_SUFFIX = {
    "FV": "front",
    "MVL": "mirror_left",
    "MVR": "mirror_right",
    "RV": "rear",
}


def camera_position_of(frame_name: str) -> str:
    suffix = Path(frame_name).stem.split("_")[-1]
    if suffix not in CAMERA_POSITION_BY_SUFFIX:
        raise ValueError(f"unrecognised camera suffix {suffix!r} in {frame_name!r}")
    return CAMERA_POSITION_BY_SUFFIX[suffix]


def list_source_frames(manifest: DataManifest) -> list[str]:
    excluded = set(manifest.selection.excluded_frames)
    frames = sorted(
        entry.name
        for entry in manifest.source.images_directory.iterdir()
        if entry.suffix.lower() in IMAGE_SUFFIXES and entry.name not in excluded
    )
    if not frames:
        raise RuntimeError(f"no frames found in {manifest.source.images_directory}")
    return frames


def generate_split(manifest: DataManifest, frames: list[str]) -> dict[str, list[str]]:
    """
    Partition frames according to the manifest's split specification.

    Frames are sorted before shuffling because directory iteration order is
    filesystem-dependent; without it the same seed yields different splits
    on different machines.
    """
    if manifest.split.method != "random_stratified":
        raise NotImplementedError(
            f"split method {manifest.split.method!r} is not implemented"
        )

    generator = random.Random(manifest.split.seed)

    if manifest.split.stratify_by == "camera_position":
        groups: dict[str, list[str]] = defaultdict(list)
        for frame in frames:
            groups[camera_position_of(frame)].append(frame)
    elif manifest.split.stratify_by is None:
        groups = {"all": list(frames)}
    else:
        raise NotImplementedError(
            f"stratify_by {manifest.split.stratify_by!r} is not implemented"
        )

    partitions: dict[str, list[str]] = {
        name: [] for name in manifest.split.partition_names
    }

    # Deterministic ordering: fractions applied in a fixed partition order,
    # with the largest partition absorbing the remainder.
    ordered_partitions = sorted(
        manifest.split.fractions.items(), key=lambda item: (-item[1], item[0])
    )

    for group_name in sorted(groups):
        group_frames = sorted(groups[group_name])
        generator.shuffle(group_frames)

        cursor = 0
        for index, (partition_name, fraction) in enumerate(ordered_partitions):
            is_last = index == len(ordered_partitions) - 1
            if is_last:
                take = len(group_frames) - cursor
            else:
                take = round(len(group_frames) * fraction)
            partitions[partition_name].extend(group_frames[cursor : cursor + take])
            cursor += take

    for name in partitions:
        partitions[name].sort()

    all_assigned = [frame for frames_ in partitions.values() for frame in frames_]
    if len(all_assigned) != len(frames):
        raise RuntimeError("frames lost during split")
    if len(set(all_assigned)) != len(all_assigned):
        raise RuntimeError("frame assigned to more than one partition")

    return partitions


def to_normalised_centre(
    annotation: SourceAnnotation, image_width: int, image_height: int
) -> tuple[float, float, float, float]:
    """Absolute pixel corners to normalised centre format, clamped to [0, 1]."""
    centre_x = ((annotation.x_minimum + annotation.x_maximum) / 2) / image_width
    centre_y = ((annotation.y_minimum + annotation.y_maximum) / 2) / image_height
    width = annotation.width / image_width
    height = annotation.height / image_height

    def clamp(value: float) -> float:
        return max(0.0, min(1.0, value))

    return clamp(centre_x), clamp(centre_y), clamp(width), clamp(height)


def build_partition(
    manifest: DataManifest,
    partition_name: str,
    frames: list[str],
    build_directory: Path,
) -> dict[str, int]:
    images_directory = build_directory / "images" / partition_name
    labels_directory = build_directory / "labels" / partition_name
    images_directory.mkdir(parents=True, exist_ok=True)
    labels_directory.mkdir(parents=True, exist_ok=True)

    reader = get_reader(manifest.source.annotation_format)
    keep_classes = set(manifest.classes.source_classes)
    minimum_area = manifest.selection.minimum_annotation_area_pixels
    maximum_per_frame = manifest.selection.maximum_annotations_per_frame

    written_annotations = 0
    frames_without_annotations = 0

    for frame_name in frames:
        source_image = (manifest.source.images_directory / frame_name).resolve()

        # Symlink rather than copy: the raw data is immutable and large.
        link_path = images_directory / frame_name
        if not link_path.exists():
            link_path.symlink_to(source_image)

        with Image.open(source_image) as image:
            image_width, image_height = image.size

        annotation_path = (
            manifest.source.annotations_directory / f"{Path(frame_name).stem}.txt"
        )
        annotations = [
            annotation
            for annotation in reader(annotation_path)
            if annotation.class_name in keep_classes
        ]

        if minimum_area is not None:
            annotations = [a for a in annotations if a.area >= minimum_area]
        if maximum_per_frame is not None:
            annotations = annotations[:maximum_per_frame]

        lines = []
        for annotation in annotations:
            class_index = manifest.classes.index_of(annotation.class_name)
            centre_x, centre_y, width, height = to_normalised_centre(
                annotation, image_width, image_height
            )
            if width <= 0 or height <= 0:
                continue
            lines.append(
                f"{class_index} {centre_x:.6f} {centre_y:.6f} {width:.6f} {height:.6f}"
            )

        written_annotations += len(lines)
        if not lines:
            frames_without_annotations += 1

        # An empty label file is a valid hard negative, not a missing label.
        label_path = labels_directory / f"{Path(frame_name).stem}.txt"
        label_path.write_text("\n".join(lines) + ("\n" if lines else ""))

    return {
        "frames": len(frames),
        "annotations": written_annotations,
        "frames_without_annotations": frames_without_annotations,
    }


def write_split_files(build_directory: Path, partitions: dict[str, list[str]]) -> None:
    splits_directory = build_directory / "splits"
    splits_directory.mkdir(parents=True, exist_ok=True)
    for partition_name, frames in partitions.items():
        path = splits_directory / f"{partition_name}.txt"
        path.write_text("\n".join(frames) + "\n")


def write_build_info(
    manifest: DataManifest,
    build_directory: Path,
    partition_statistics: dict[str, dict[str, int]],
) -> None:
    """
    Record what produced this build.

    The manifest hash is the important field: the trainer compares it against
    the current manifest and refuses to run on a stale build.
    """
    info = {
        "manifest_name": manifest.identity.name,
        "manifest_path": str(manifest.path),
        "manifest_hash": hash_file(manifest.path),
        "built_at": datetime.now(timezone.utc).isoformat(),
        "git_commit": git_commit(),
        "git_dirty": git_is_dirty(),
        "classes": manifest.classes.mapping,
        "partitions": partition_statistics,
    }
    (build_directory / "build_info.json").write_text(json.dumps(info, indent=2))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", required=True)
    parser.add_argument(
        "--force",
        action="store_true",
        help="Remove an existing build directory before rebuilding.",
    )
    parser.add_argument(
        "--skip-source-verification",
        action="store_true",
        help="Skip checking source frame count against manifest statistics.",
    )
    arguments = parser.parse_args()

    manifest = load_manifest(arguments.manifest)
    print(f"manifest: {manifest}")

    if not arguments.skip_source_verification:
        verify_source_matches_statistics(manifest)
        print(f"source verified: {manifest.source.images_directory}")

    build_directory = manifest.build_directory
    if build_directory.exists():
        if not arguments.force:
            raise SystemExit(
                f"{build_directory} already exists; pass --force to rebuild."
            )
        shutil.rmtree(build_directory)
    build_directory.mkdir(parents=True)

    frames = list_source_frames(manifest)
    partitions = generate_split(manifest, frames)
    write_split_files(build_directory, partitions)

    partition_statistics: dict[str, dict[str, int]] = {}
    for partition_name in manifest.split.partition_names:
        statistics = build_partition(
            manifest, partition_name, partitions[partition_name], build_directory
        )
        partition_statistics[partition_name] = statistics
        print(
            f"{partition_name}: {statistics['frames']} frames, "
            f"{statistics['annotations']} annotations, "
            f"{statistics['frames_without_annotations']} without annotations"
        )

    write_build_info(manifest, build_directory, partition_statistics)
    print(f"\nbuild written to {build_directory.resolve()}")


if __name__ == "__main__":
    main()